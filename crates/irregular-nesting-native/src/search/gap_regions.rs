/// Exact canonical convex-hull-minus-occupied-union regions.
///
/// TS: `intrinsicGapRegions.ts:42-72` (`deriveCanonicalIntrinsicGapRegions`).
pub fn derive_canonical_intrinsic_gap_regions(
    placed: &[IrregularPlacedPiece],
) -> Option<Vec<CanonicalIntrinsicGapRegion>> {
    let mut occupied: Vec<CanonicalGridPath> = Vec::with_capacity(placed.len());
    for piece in placed {
        occupied.push(placed_path(piece)?);
    }
    let flattened: Vec<CanonicalGridPoint> = occupied.iter().flatten().copied().collect();
    let hull = canonical_grid_convex_hull(&flattened)?;
    if hull.len() < 3 {
        return Some(Vec::new());
    }

    let subject_paths: Paths64 = occupied.iter().map(|path| to_clipper_path(path)).collect();
    let mut occupied_tree = PolyTree64::new();
    boolean_op_with_poly_tree(
        ClipType::Union,
        Some(&subject_paths),
        None,
        &mut occupied_tree,
        FillRule::EvenOdd,
    );

    let oriented_hull = canonical_grid_counter_clockwise(&hull).unwrap_or_else(|| hull.clone());
    let hull_subject: Paths64 = vec![to_clipper_path(&oriented_hull)];
    let occupied_union = poly_tree_to_paths64(&occupied_tree);
    let mut gap_tree = PolyTree64::new();
    boolean_op_with_poly_tree(
        ClipType::Difference,
        Some(&hull_subject),
        Some(&occupied_union),
        &mut gap_tree,
        FillRule::NonZero,
    );

    let mut regions: Vec<CanonicalIntrinsicGapRegion> = Vec::new();
    if !collect_regions(&gap_tree, PolyTree64::ROOT, &hull, &mut regions) {
        return None;
    }

    regions.sort_by(|first, second| {
        let first_area = first
            .doubled_area_grid2
            .parse::<BigInt>()
            .expect("doubled_area_grid2 is always a valid decimal BigInt string");
        let second_area = second
            .doubled_area_grid2
            .parse::<BigInt>()
            .expect("doubled_area_grid2 is always a valid decimal BigInt string");
        match first_area.cmp(&second_area) {
            Ordering::Equal => locale_compare_keys(&first.canonical_key, &second.canonical_key),
            other => other,
        }
    });
    Some(regions)
}

/// Exact zero-positive-area test for candidate minus one gap solid.
///
/// TS: `intrinsicGapRegions.ts:75-106` (`candidateContainedInIntrinsicGap`).
pub fn candidate_contained_in_intrinsic_gap(
    moving: &TransformedCollisionGeometry,
    point: IrregularPoint,
    region: &CanonicalIntrinsicGapRegion,
) -> bool {
    let mut candidate_path: CanonicalGridPath = Vec::with_capacity(moving.polygon.points.len());
    for source_point in &moving.polygon.points {
        let Some(x) = to_grid_mm(source_point.x + point.x) else {
            return false;
        };
        let Some(y) = to_grid_mm(source_point.y + point.y) else {
            return false;
        };
        candidate_path.push(CanonicalGridPoint::new(x, y));
    }

    let Some(boundary) = canonical_grid_counter_clockwise(&region.boundary) else {
        return false;
    };
    let mut holes: Vec<CanonicalGridPath> = Vec::with_capacity(region.holes.len());
    for hole in &region.holes {
        let Some(clockwise_hole) = canonical_grid_clockwise(hole) else {
            return false;
        };
        holes.push(clockwise_hole);
    }

    let mut solid: Paths64 = Vec::with_capacity(1 + holes.len());
    solid.push(to_clipper_path(&boundary));
    for hole in &holes {
        solid.push(to_clipper_path(hole));
    }

    let subject_path = canonical_grid_counter_clockwise(&candidate_path).unwrap_or(candidate_path);
    let subject: Paths64 = vec![to_clipper_path(&subject_path)];

    let mut difference = PolyTree64::new();
    boolean_op_with_poly_tree(
        ClipType::Difference,
        Some(&subject),
        Some(&solid),
        &mut difference,
        FillRule::NonZero,
    );

    total_positive_doubled_area(&difference, PolyTree64::ROOT) == Some(BigInt::from(0))
}

