/// TS: `intrinsicGapRegions.ts:108-163` (`collectRegions`).
fn collect_regions(
    tree: &PolyTree64,
    parent: usize,
    hull: &CanonicalGridPath,
    result: &mut Vec<CanonicalIntrinsicGapRegion>,
) -> bool {
    for index in 0..tree.count(parent) {
        let child = tree.child(parent, index);
        if !tree.is_hole(child) {
            if let Some(child_polygon) = tree.poly(child) {
                let child_path = to_canonical_grid_path(child_polygon);
                let Some(outer_doubled_area) = canonical_grid_absolute_doubled_area(&child_path)
                else {
                    return false;
                };
                let mut net_doubled_area = outer_doubled_area;
                let mut holes: Vec<CanonicalGridPath> = Vec::new();
                for hole_index in 0..tree.count(child) {
                    let hole = tree.child(child, hole_index);
                    if tree.is_hole(hole) {
                        if let Some(hole_polygon) = tree.poly(hole) {
                            let hole_path = to_canonical_grid_path(hole_polygon);
                            let Some(hole_doubled_area) =
                                canonical_grid_absolute_doubled_area(&hole_path)
                            else {
                                return false;
                            };
                            holes.push(hole_path);
                            net_doubled_area -= hole_doubled_area;
                        }
                    }
                }

                let aabb = path_bounds(&child_path);
                let area_mm2 = doubled_grid_area_to_mm2(&net_doubled_area);
                let boundary = canonical_grid_counter_clockwise(&child_path);
                if net_doubled_area <= BigInt::from(0)
                    || aabb.is_none()
                    || area_mm2.is_none()
                    || boundary.is_none()
                {
                    return false;
                }
                let aabb = aabb.expect("checked above");
                let area_mm2 = area_mm2.expect("checked above");
                let boundary = boundary.expect("checked above");

                let holes_len = holes.len();
                let mut ordered_holes: Vec<CanonicalGridPath> = holes
                    .into_iter()
                    .filter_map(|path| canonical_grid_clockwise(&path))
                    .collect();
                ordered_holes.sort_by(|first, second| {
                    locale_compare_keys(&canonical_ring(first), &canonical_ring(second))
                });
                if ordered_holes.len() != holes_len {
                    return false;
                }

                let kind = if path_touches_boundary(&boundary, hull) {
                    CanonicalIntrinsicGapRegionKind::HullOpenGap
                } else {
                    CanonicalIntrinsicGapRegionKind::EnclosedCavity
                };
                let canonical_key = format!(
                    "{}|{}",
                    canonical_ring(&boundary),
                    ordered_holes
                        .iter()
                        .map(|hole| canonical_ring(hole))
                        .collect::<Vec<_>>()
                        .join("|")
                );
                result.push(CanonicalIntrinsicGapRegion {
                    kind,
                    boundary,
                    holes: ordered_holes,
                    area_mm2,
                    doubled_area_grid2: net_doubled_area.to_string(),
                    aabb,
                    canonical_key,
                });
            }
        }
        if !collect_regions(tree, child, hull, result) {
            return false;
        }
    }
    true
}

/// TS: `intrinsicGapRegions.ts:165-175` (`pathTouchesBoundary`). Note the
/// caller's argument order: `path` is the candidate region's own boundary
/// ring, `boundary` is the enclosing hull.
fn path_touches_boundary(path: &[CanonicalGridPoint], boundary: &[CanonicalGridPoint]) -> bool {
    path.iter().any(|point| {
        boundary.iter().enumerate().any(|(index, start)| {
            let Some(end) = boundary.get((index + 1) % boundary.len()) else {
                return false;
            };
            canonical_grid_point_on_segment(*point, *start, *end)
        })
    })
}

/// TS: `intrinsicGapRegions.ts:177-189` (`placedPath`).
fn placed_path(placed: &IrregularPlacedPiece) -> Option<CanonicalGridPath> {
    let mut path: CanonicalGridPath =
        Vec::with_capacity(placed.collision_geometry.polygon.points.len());
    for point in &placed.collision_geometry.polygon.points {
        let x = to_grid_mm(point.x + placed.placement.transform.translate_x)?;
        let y = to_grid_mm(point.y + placed.placement.transform.translate_y)?;
        path.push(CanonicalGridPoint::new(x, y));
    }
    let signed_doubled_area = canonical_grid_signed_doubled_area(&path)?;
    if path.len() >= 3 && signed_doubled_area != BigInt::from(0) {
        canonical_grid_counter_clockwise(&path)
    } else {
        None
    }
}

/// TS: `intrinsicGapRegions.ts:191-211` (`totalPositiveDoubledArea`).
fn total_positive_doubled_area(tree: &PolyTree64, parent: usize) -> Option<BigInt> {
    let mut total = BigInt::from(0);
    if visit_total_positive_doubled_area(tree, parent, &mut total) {
        Some(total)
    } else {
        None
    }
}

fn visit_total_positive_doubled_area(tree: &PolyTree64, parent: usize, total: &mut BigInt) -> bool {
    for index in 0..tree.count(parent) {
        let child = tree.child(parent, index);
        if !tree.is_hole(child) {
            if let Some(child_polygon) = tree.poly(child) {
                let child_path = to_canonical_grid_path(child_polygon);
                let Some(doubled_area) = canonical_grid_absolute_doubled_area(&child_path) else {
                    return false;
                };
                *total += doubled_area;
            }
        }
        if !visit_total_positive_doubled_area(tree, child, total) {
            return false;
        }
    }
    true
}

/// TS: `intrinsicGapRegions.ts:213-227` (`pathBounds`).
fn path_bounds(path: &[CanonicalGridPoint]) -> Option<CanonicalIntrinsicGapRegionAabb> {
    let first = *path.first()?;
    let mut min_x = first.x;
    let mut min_y = first.y;
    let mut max_x = first.x;
    let mut max_y = first.y;
    for point in &path[1..] {
        min_x = js_math::min(min_x, point.x);
        min_y = js_math::min(min_y, point.y);
        max_x = js_math::max(max_x, point.x);
        max_y = js_math::max(max_y, point.y);
    }
    Some(CanonicalIntrinsicGapRegionAabb {
        min_x,
        min_y,
        max_x,
        max_y,
    })
}

/// TS: `intrinsicGapRegions.ts:229-238` (`canonicalRing`). Enumerates every
/// rotation x direction variant of the ring's point list and keeps the
/// **default**-sorted (ordinal, not locale-aware — characterization doc §12
/// hazard 4) smallest one; distinct from, and not to be confused with,
/// `crate::canonical_grid::layout`'s own (differently-implemented)
/// `canonical_ring` helper for a different TS source file.
fn canonical_ring(path: &[CanonicalGridPoint]) -> String {
    let reversed: CanonicalGridPath = path.iter().rev().copied().collect();
    let mut best: Option<String> = None;
    for sequence in [path, reversed.as_slice()] {
        for offset in 0..sequence.len() {
            let joined = sequence[offset..]
                .iter()
                .chain(sequence[..offset].iter())
                .map(|point| {
                    format!(
                        "{},{}",
                        number_to_js_string(point.x),
                        number_to_js_string(point.y)
                    )
                })
                .collect::<Vec<_>>()
                .join(";");
            best = Some(match best {
                None => joined,
                Some(current) => {
                    if cmp_js_code_units(&joined, &current) == Ordering::Less {
                        joined
                    } else {
                        current
                    }
                }
            });
        }
    }
    best.unwrap_or_default()
}

