fn to_clipper_path(path: &[CanonicalGridPoint]) -> Path64 {
    path.iter()
        .map(|point| Point64::new(point.x, point.y, 0.0))
        .collect()
}

fn to_canonical_grid_path(path: &[Point64]) -> CanonicalGridPath {
    path.iter()
        .map(|point| CanonicalGridPoint::new(point.x, point.y))
        .collect()
}

