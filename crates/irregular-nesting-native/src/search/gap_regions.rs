    #[test]
    fn single_square_hull_degenerates_to_no_regions() {
        // A single square's convex hull equals its own occupied area exactly,
        // so the hull-minus-occupied difference is empty.
        let placed = vec![square_piece("a", 0.0, 0.0, 10.0)];
        let regions = derive_canonical_intrinsic_gap_regions(&placed).expect("must succeed");
        assert!(regions.is_empty());
    }

    #[test]
    fn two_diagonal_squares_produce_one_hull_open_gap() {
        // Two squares placed diagonally: their convex hull is a hexagon in
        // which both squares are corner-anchored (each touches two hull
        // edges), so the hull-minus-occupied difference is one single
        // connected band running between them (not two disjoint triangles),
        // and that band touches the hull boundary on both sides.
        let placed = vec![
            square_piece("a", 0.0, 0.0, 10.0),
            square_piece("b", 20.0, 20.0, 10.0),
        ];
        let regions = derive_canonical_intrinsic_gap_regions(&placed).expect("must succeed");
        assert_eq!(regions.len(), 1, "one connected open-gap band");
        assert_eq!(
            regions[0].kind,
            CanonicalIntrinsicGapRegionKind::HullOpenGap
        );
        assert!(regions[0].holes.is_empty());
        assert!(regions[0].area_mm2 > 0.0);
    }

    #[test]
    fn picture_frame_encloses_a_cavity() {
        // A closed rectangular frame (four rectangles fully surrounding a
        // 10x10 hole in the middle) has a hull equal to its own occupied
        // outer boundary, so the hole never touches the hull boundary: it
        // must be an enclosed cavity, not a hull-open gap.
        let placed = vec![
            rect_piece("top", 0.0, 20.0, 30.0, 10.0),
            rect_piece("bottom", 0.0, 0.0, 30.0, 10.0),
            rect_piece("left", 0.0, 10.0, 10.0, 10.0),
            rect_piece("right", 20.0, 10.0, 10.0, 10.0),
        ];
        let regions = derive_canonical_intrinsic_gap_regions(&placed).expect("must succeed");
        assert_eq!(
            regions.len(),
            1,
            "exactly one enclosed cavity in the middle"
        );
        assert_eq!(
            regions[0].kind,
            CanonicalIntrinsicGapRegionKind::EnclosedCavity
        );
        assert!(regions[0].holes.is_empty());
        // The cavity is exactly the 10x10 hole in grid units (0.001mm).
        assert_eq!(
            regions[0].doubled_area_grid2.parse::<BigInt>().unwrap(),
            BigInt::from(2) * BigInt::from(10_000) * BigInt::from(10_000)
        );
    }

