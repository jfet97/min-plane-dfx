/// Groups prepared copies by both declared interchangeability and exact
/// collision shape.
///
/// TS: `intrinsicStrictFamilyPortfolio.ts:95-121`
/// (`groupIntrinsicCollisionFamilies`). Output order is **first-occurrence
/// order** while scanning `pieces` left to right — a JS `Map`'s key
/// insertion order, which `.set()` on an existing key never disturbs
/// (characterization doc §5 item 9, §12 hazard 5). Reproduced here with an
/// explicit `Vec` (insertion order) alongside a `HashMap<String, usize>`
/// lookup index, never a bare hash map relied on for iteration order.
pub fn group_intrinsic_collision_families(
    pieces: &[IrregularPreparedPiece],
) -> Vec<IntrinsicCollisionFamily> {
    struct GroupBuilder {
        key: String,
        members: Vec<IrregularPreparedPiece>,
        first_baseline_index: f64,
    }

    let mut groups: Vec<GroupBuilder> = Vec::new();
    let mut index_by_key: HashMap<String, usize> = HashMap::new();

    for (index, piece) in pieces.iter().enumerate() {
        let key = intrinsic_collision_family_key(piece);
        match index_by_key.get(&key) {
            Some(&group_index) => {
                groups[group_index].members.push(piece.clone());
            }
            None => {
                index_by_key.insert(key.clone(), groups.len());
                groups.push(GroupBuilder {
                    key,
                    members: vec![piece.clone()],
                    first_baseline_index: index as f64,
                });
            }
        }
    }

    groups
        .into_iter()
        .map(|group| {
            let measurements = group.members.first().and_then(|first| {
                measure_collision_polygon(&first.collision_geometry.collision_polygon.points)
            });
            IntrinsicCollisionFamily {
                key: group.key,
                members: group.members,
                first_baseline_index: group.first_baseline_index,
                collision_area_mm2: measurements.as_ref().map_or(0.0, |m| m.area_mm2),
                maximum_side_mm: measurements.as_ref().map_or(0.0, |m| m.maximum_side_mm),
                aspect_ratio: measurements.as_ref().map_or(1.0, |m| m.aspect_ratio),
            }
        })
        .collect()
}

/// Stable collision-family key with source-copy identity intentionally
/// excluded.
///
/// TS: `intrinsicStrictFamilyPortfolio.ts:124-130` (`intrinsicCollisionFamilyKey`).
pub fn intrinsic_collision_family_key(piece: &IrregularPreparedPiece) -> String {
    let interchangeability_key = piece
        .interchangeability_key
        .as_deref()
        .unwrap_or_else(|| piece.source.id.as_str());
    let cyclic_key =
        canonical_cyclic_polygon_key(&piece.collision_geometry.collision_polygon.points);
    json_stringify_string_pair(interchangeability_key, &cyclic_key)
}

