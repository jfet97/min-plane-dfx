/// TS: `intrinsicStrictFamilyPortfolio.ts:41-48` (`IntrinsicCollisionFamily`).
///
/// `collision_area_mm2`/`maximum_side_mm`/`aspect_ratio` are derived once
/// from `members[0]` only (`:109-119`), never averaged or re-validated
/// against other members — other members are *assumed*, not verified, to be
/// geometrically identical because [`intrinsic_collision_family_key`]
/// already encodes the canonical polygon shape. Do not "improve" this by
/// computing per-member statistics.
#[derive(Debug, Clone, PartialEq)]
pub struct IntrinsicCollisionFamily {
    pub key: String,
    pub members: Vec<IrregularPreparedPiece>,
    /// TS `number` (`firstBaselineIndex`); mirrored as `f64` per this
    /// crate's number-fidelity convention (`domain` module doc), not a
    /// narrower Rust integer type, even though every real value is a
    /// non-negative array index.
    pub first_baseline_index: f64,
    pub collision_area_mm2: f64,
    pub maximum_side_mm: f64,
    pub aspect_ratio: f64,
}

