fn portfolio_status_str(
    status: irregular_nesting_native::result::IrregularPortfolioStatus,
) -> &'static str {
    use irregular_nesting_native::result::IrregularPortfolioStatus as S;
    match status {
        S::Completed => "completed",
        S::Partial => "budget-expired",
        S::Failed => "no-valid-result",
    }
}

fn portfolio_termination_reason_str(
    reason: irregular_nesting_native::result::IrregularPortfolioTerminationReason,
) -> &'static str {
    use irregular_nesting_native::result::IrregularPortfolioTerminationReason as R;
    match reason {
        R::CapacitySubsetSettled => "capacity_subset_settled",
        R::SharedArchiveCompleted => "shared_archive_completed",
    }
}

fn search_source_str(
    source: irregular_nesting_native::result::IrregularSearchSource,
) -> &'static str {
    use irregular_nesting_native::result::IrregularSearchSource as Src;
    match source {
        Src::SharedArchive => "shared-archive",
    }
}

fn encode_portfolio(
    portfolio: &irregular_nesting_native::result::IrregularPortfolioResult,
) -> Value {
    serde_json::json!({
        "status": portfolio_status_str(portfolio.status),
        "terminationReason": portfolio_termination_reason_str(portfolio.termination_reason),
        "source": search_source_str(portfolio.source),
        "placements": portfolio.placements.iter().map(encode_placement).collect::<Vec<_>>(),
        "unplacedPieceIds": portfolio.unplaced_piece_ids.iter().map(|id| id.as_str().to_string()).collect::<Vec<_>>(),
        "score": encode_score(&portfolio.score),
    })
}

