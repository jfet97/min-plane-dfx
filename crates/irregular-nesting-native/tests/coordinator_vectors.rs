//! Coordinator integration coverage for
//! `crates/irregular-nesting-native/src/result/{mod,coordinator,materialize,progress}.rs`
//! (the port of `src/workers/algorithm/irregular/computeIrregularNesting.ts`)
//! plus the `capacity::mode` orchestration it now wires directly
//! (`run_intrinsic_capacity_mode`/`run_intrinsic_capacity_scheduler_cold_quantum`,
//! ported from `intrinsicCapacityMode.ts`).
//!
//! The first four tests below (`archive_ineligible_settings_return_a_typed_routing_error`
//! through `history_mode_off_suppresses_state_snapshots_but_not_progress`) are
//! the original hand-built structural/behavioral integration tests written
//! before the full differential suite existed; they exercise coordinator
//! wiring the vector suite below does not specifically target (progress
//! event emission order, snapshot suppression under `historyMode: 'off'`)
//! and are kept unchanged.
//!
//! `full_job_vectors_match_ts_oracle` is the real cross-language
//! differential suite the task brief asks for: it loads
//! `tests/vectors/coordinator.json` (generated by
//! `scripts/rust-parity/dump-coordinator.ts` from the REAL, Effect-layered
//! production `computeIrregularNesting` -- see that script's own top doc for
//! the exact layer stack, matching `nesting.worker.ts`'s
//! `computeIrregularWorkerResult` precisely), reconstructs each case's
//! `NestingRequest`/`IrregularNestingSettings` in Rust, calls
//! `result::coordinator::compute_irregular_nesting`, and asserts the real
//! Rust result's own semantic projection (placements bit-exact, score,
//! placed/unplaced partitions, canonical hashes, snapshot sequences,
//! portfolio/capacity/scheduler traces, statuses) exactly reproduces the
//! recorded TS oracle output. Every `performance.now()`-derived field
//! (`*RuntimeMs`, `*Ms`, `elapsedMs`) is excluded from both sides as
//! documented non-semantic timing data -- there is no `timingNow` seam in
//! `computeIrregularNesting.ts` itself (confirmed by direct source grep).

